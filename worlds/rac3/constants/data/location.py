UT_MAPPING: dict[str, int] = {}


@dataclass
class RAC3LOCATIONDATA:
    """Data class for each location"""
    ID: int = 0
    REGION: str = RAC3REGION.GALAXY
    CHECK_ADDRESS: list[RAC3ADDRESSDATA] = None
    AP_CODE: int = None
    TAGS: set[str] = None

    def __init__(self,
                 idx: int,
                 region: str = RAC3REGION.GALAXY,
                 check: list[RAC3ADDRESSDATA] | None = None,
                 tags: set[str] | None = None):
        self.ID = idx
        self.REGION = region
        self.CHECK_ADDRESS = check if check else []
        self.AP_CODE = idx + RAC3STATUS.APCODE
        self.TAGS = tags if tags else set()

    @staticmethod
    def construct(location_name: str):
        """Construct the given location data for the location data table"""
        planet_name: str = _LOCATION_NAME_TO_REGION[location_name]
        planet_id: int = RAC3_REGION_DATA_TABLE[planet_name].ID
        loc_id: int = _LOCATION_NAME_TO_ID[location_name]
        tags: set[str] = set(_LOCATION_NAME_TO_TAG[location_name])
        if planet_id:
            section_id: int = _LOCATION_NAME_TO_SECTION[location_name]
            UT_MAPPING[f"{planet_id}/{loc_id}"] = loc_id + RAC3STATUS.APCODE
            UT_MAPPING[f"{section_id}/{loc_id}"] = loc_id + RAC3STATUS.APCODE
            tags.union({planet_name})
        else:
            match planet_name:
                case RAC3REGION.SKIDD_CUTSCENE:
                    UT_MAPPING[f"0/12/{loc_id}"] = loc_id + RAC3STATUS.APCODE
                    UT_MAPPING[f"12/2/{loc_id}"] = loc_id + RAC3STATUS.APCODE
                    UT_MAPPING[f"0/13/{loc_id}"] = loc_id + RAC3STATUS.APCODE
                    UT_MAPPING[f"13/6/{loc_id}"] = loc_id + RAC3STATUS.APCODE
                    tags.union({RAC3REGION.HOLOSTAR_STUDIOS, RAC3REGION.BLACKWATER_CITY})
                case RAC3REGION.NANOTECH:
                    section_id = _LOCATION_NAME_TO_SECTION[location_name]
                    UT_MAPPING[f"0/{section_id}/{loc_id}"] = loc_id + RAC3STATUS.APCODE
                case RAC3REGION.NGPLUS:
                    UT_MAPPING[f"3/{loc_id}"] = loc_id + RAC3STATUS.APCODE
                    UT_MAPPING[f"0/{loc_id}"] = loc_id + RAC3STATUS.APCODE
                    tags.union({RAC3REGION.NGPLUS, RAC3REGION.STARSHIP_PHOENIX})
        check: list[RAC3ADDRESSDATA] = []
        for item in _LOCATION_NAME_TO_ADDRESS[location_name]:
            check += [RAC3ADDRESSDATA(item)]
        return RAC3LOCATIONDATA(loc_id, planet_name, check, tags)


