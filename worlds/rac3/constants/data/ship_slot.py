"""This module contains the dataclass for which levels are unlocked in the game"""
from dataclasses import dataclass

from worlds.rac3.constants.ship_slot import RAC3SHIPSLOT
from worlds.rac3.constants.status import RAC3STATUS


@dataclass
class RAC3SHIPDATA:
    ID: int
    SLOT_ADDRESS: int

    def __init__(self, slot: int):
        self.ID = slot + 1
        self.SLOT_ADDRESS = 4 * slot + RAC3STATUS.PLANET_SLOT_ADDRESS


